package com.revature.oop;

public class Basics {
    /*
        When thinking of the pillars of Object-Oriented Programming remember
        APIE
        - Abstraction
        - Polymorphism
        - Inheritance
        - Encapsulation

        Abstraction is about hiding complexity: other programmers using your code
        or other parts of your application interfacing with your code don't need
        to see or understand the underlying complexity of your code

        Polymorphism is about how a resource can take on many forms. We will focus
        on method polymorphism, specifically overloading and overwriting

        Inheritance is the ability to define your attributes and behaviors in one
        location and then make those resources accessible in multiple other classes.
        We will look at Abstract Classes and Interfaces for this

        Encapsulation is about controlling access to the attributes and sometimes
        behaviors of your classes. We will look at the Java bean design pattern to
        see this in action
     */
}
